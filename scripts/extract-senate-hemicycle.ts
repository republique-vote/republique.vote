import { writeFile } from "node:fs/promises";
import { join } from "node:path";

// Seat plan of the Senate, read from the hemicycle drawn on senat.fr: only the
// center of each numbered seat is kept, the chart draws its own seats. Rerun
// when the Senate renumbers the room.
const SCRIPT_URL = "https://www.senat.fr/assets/scripts/senat.js";
const OUTPUT = join(
  process.cwd(),
  "src/components/polls/poll-detail/senate-hemicycle-plan.ts"
);
const SEAT_PATTERN = /\{id:(\d+),cx:([\d.]+),cy:([\d.]+)\}/g;

async function main() {
  const script = await (await fetch(SCRIPT_URL)).text();
  const seats = new Map<number, [number, number]>();
  for (const [, id, cx, cy] of script.matchAll(SEAT_PATTERN)) {
    seats.set(Number(id), [Number(cx), Number(cy)]);
  }
  if (seats.size < 300) {
    throw new Error(`Only ${seats.size} seats found, the page changed`);
  }

  const lines = [...seats]
    .sort(([a], [b]) => a - b)
    .map(([seat, [x, y]]) => `  ${seat}: [${x}, ${y}],`);
  await writeFile(
    OUTPUT,
    `// Generated by scripts/extract-senate-hemicycle.ts from the seat plan of
// senat.fr: center of each numbered seat, in the plan's units
export const SENATE_HEMICYCLE_PLAN: Record<number, [number, number]> = {
${lines.join("\n")}
};
`
  );
  console.log(`[hemicycle] ${seats.size} Senate seats written to ${OUTPUT}`);
}

main().catch((err) => {
  console.error("[hemicycle] Extraction failed:", err);
  process.exit(1);
});
