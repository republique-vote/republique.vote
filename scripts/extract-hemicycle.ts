import { writeFile } from "node:fs/promises";
import { join } from "node:path";

// Seat plan of the hemicycle, read from the interactive map of the Assemblée
// website: only the center of each numbered seat is kept, the chart draws its
// own seats. Rerun when the Assemblée renumbers the room.
const PLAN_URL =
  "https://www.assemblee-nationale.fr/dyn/vos-deputes/hemicycle?siege=1";
const OUTPUT = join(
  process.cwd(),
  "src/components/polls/poll-detail/hemicycle-plan.ts"
);
const COMMAND = /[MLlZz]/;
const SEAT_PATTERN = /d="([^"]+)"\s+class="place" id="p(\d+)"/g;

// Seats are small polygons made of M, L and l commands: the center of their
// bounding box is the center of the seat
function polygonCenter(path: string) {
  const tokens = path.match(/[MLlZz]|-?\d*\.?\d+/g) ?? [];
  const xs: number[] = [];
  const ys: number[] = [];
  let command = "M";
  let x = 0;
  let y = 0;
  let i = 0;
  while (i < tokens.length) {
    if (COMMAND.test(tokens[i])) {
      command = tokens[i];
      i++;
      continue;
    }
    const a = Number(tokens[i]);
    const b = Number(tokens[i + 1]);
    i += 2;
    x = command === "l" ? x + a : a;
    y = command === "l" ? y + b : b;
    xs.push(x);
    ys.push(y);
  }
  return [
    (Math.min(...xs) + Math.max(...xs)) / 2,
    (Math.min(...ys) + Math.max(...ys)) / 2,
  ];
}

async function main() {
  const html = await (await fetch(PLAN_URL)).text();
  const seats = [...html.matchAll(SEAT_PATTERN)]
    .map(([, path, seat]) => {
      const [x, y] = polygonCenter(path);
      return [Number(seat), Math.round(x * 10) / 10, Math.round(y * 10) / 10];
    })
    .sort((a, b) => a[0] - b[0]);
  if (seats.length < 500) {
    throw new Error(`Only ${seats.length} seats found, the page changed`);
  }

  const lines = seats.map(([seat, x, y]) => `  ${seat}: [${x}, ${y}],`);
  await writeFile(
    OUTPUT,
    `// Generated by scripts/extract-hemicycle.ts from the seat plan of the
// Assemblée website: center of each numbered seat, in the plan's units
export const HEMICYCLE_PLAN: Record<number, [number, number]> = {
${lines.join("\n")}
};
`
  );
  console.log(`[hemicycle] ${seats.length} seats written to ${OUTPUT}`);
}

main().catch((err) => {
  console.error("[hemicycle] Extraction failed:", err);
  process.exit(1);
});
