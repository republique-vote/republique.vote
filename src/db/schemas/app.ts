// Plain-language summary of a poll, generated by an AI model from the
// explanatory memorandum. Model and prompt version are kept so readers know
// how it was made and summaries can be regenerated when the prompt changes.
export const pollSummary = pgTable("poll_summary", {
  pollId: text("poll_id")
    .primaryKey()
    .references(() => poll.id, { onDelete: "cascade" }),
  simpleSentence: text("simple_sentence").notNull(),
  plainTitle: text("plain_title").notNull(),
  summary: text("summary").notNull(),
  // Empty when the model was not sure about the current situation
  context: text("context"),
  changes: jsonb("changes").$type<string[]>().notNull(),
  model: text("model").notNull(),
  promptVersion: text("prompt_version").notNull(),
  generatedAt: text("generated_at")
    .notNull()
    .$defaultFn(() => new Date().toISOString()),
});

// Readers flag summaries that are wrong, unclear or biased. The prompt
// version tells which instructions produced the flagged summary.
export const summaryReport = pgTable("summary_report", {
  id: text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID()),
  pollId: text("poll_id")
    .notNull()
    .references(() => poll.id, { onDelete: "cascade" }),
  promptVersion: text("prompt_version").notNull(),
  message: text("message").notNull(),
  createdAt: text("created_at")
    .notNull()
    .$defaultFn(() => new Date().toISOString()),
});

// Members of parliament and government, from the Assemblée nationale open
// data (AMO). Only what the poll page shows is kept.
export const deputy = pgTable("deputy", {
  id: text("id").primaryKey(),
  firstName: text("first_name").notNull(),
  lastName: text("last_name").notNull(),
  // Legislature folder holding the official photo, null when none exists
  photoLegislature: text("photo_legislature"),
  syncedAt: text("synced_at")
    .notNull()
    .$defaultFn(() => new Date().toISOString()),
});

// Who proposed and cosigned each bill. The political group is the one the
// person belonged to when signing, not their current one.
export const pollAuthor = pgTable(
  "poll_author",
  {
    pollId: text("poll_id")
      .notNull()
      .references(() => poll.id, { onDelete: "cascade" }),
    deputyId: text("deputy_id")
      .notNull()
      .references(() => deputy.id),
    role: text("role", { enum: ["author", "cosignatory"] }).notNull(),
    position: integer("position").notNull(),
    signedAt: text("signed_at"),
    groupName: text("group_name"),
    groupAbbrev: text("group_abbrev"),
    groupColor: text("group_color"),
    // Government role when signing ("Premier ministre", "Ministre de ...")
    functionTitle: text("function_title"),
  },
  (t) => [unique().on(t.pollId, t.deputyId)]
);

// How each political group voted on the official scrutin of a poll. Absent
// members are the group size minus everyone listed.
export const scrutinGroup = pgTable("scrutin_group", {
  pollId: text("poll_id")
    .notNull()
    .references(() => poll.id, { onDelete: "cascade" }),
  groupRef: text("group_ref").notNull(),
  name: text("name").notNull(),
  abbrev: text("abbrev"),
  color: text("color"),
  // Mean seat number: seats are numbered from the right of the hemicycle,
  // so sorting by it descending gives the real left-to-right placement
  seatOrder: integer("seat_order").notNull(),
  members: integer("members").notNull(),
  forCount: integer("for_count").notNull(),
  againstCount: integer("against_count").notNull(),
  abstentionCount: integer("abstention_count").notNull(),
  nonVotingCount: integer("non_voting_count").notNull(),
});

// Each member's position on the official scrutin, as published by the
// Assemblée nationale. "absent" is deduced: group members on the scrutin date
// who are not listed, stored only when the deduced group size matches the
// published one
export const scrutinVote = pgTable(
  "scrutin_vote",
  {
    pollId: text("poll_id")
      .notNull()
      .references(() => poll.id, { onDelete: "cascade" }),
    deputyId: text("deputy_id")
      .notNull()
      .references(() => deputy.id),
    groupRef: text("group_ref").notNull(),
    position: text("position", {
      enum: ["for", "against", "abstention", "nonVoting", "absent"],
    }).notNull(),
    seat: integer("seat"),
  },
  (t) => [unique().on(t.pollId, t.deputyId)]
);

export const senator = pgTable("senator", {
  // Senate matricule, e.g. "19591F"
  id: text("id").primaryKey(),
  firstName: text("first_name").notNull(),
  lastName: text("last_name").notNull(),
  // Official photo, only known for sitting senators
  photoUrl: text("photo_url"),
  syncedAt: text("synced_at")
    .notNull()
    .$defaultFn(() => new Date().toISOString()),
});

// How each senator voted on the latest public vote of the Senate on the whole
// text, with their political group on that day and their seat when published
export const senateVote = pgTable("senate_vote", {
  // "pollId:senatorId": a single-column key, as drizzle-kit push reads
  // two-column unique constraints in a varying column order and recreates them
  id: text("id").primaryKey(),
  pollId: text("poll_id")
    .notNull()
    .references(() => poll.id, { onDelete: "cascade" }),
  // Scrutin the rows come from, e.g. "2025-95": a later reading replaces them
  scrutinRef: text("scrutin_ref").notNull(),
  senatorId: text("senator_id")
    .notNull()
    .references(() => senator.id),
  groupCode: text("group_code").notNull(),
  groupName: text("group_name").notNull(),
  position: text("position", {
    enum: ["for", "against", "abstention", "nonVoting"],
  }).notNull(),
  seat: integer("seat"),
});

// Political groups of deputies and senators on a vote of the Congrès
export const congressGroup = pgTable("congress_group", {
  // "pollId:groupRef", see senateVote
  id: text("id").primaryKey(),
  pollId: text("poll_id")
    .notNull()
    .references(() => poll.id, { onDelete: "cascade" }),
  groupRef: text("group_ref").notNull(),
  name: text("name").notNull(),
  color: text("color"),
  members: integer("members").notNull(),
  forCount: integer("for_count").notNull(),
  againstCount: integer("against_count").notNull(),
  abstentionCount: integer("abstention_count").notNull(),
  nonVotingCount: integer("non_voting_count").notNull(),
});

// How each member of parliament voted at the Congrès. Deputies and senators
// share the actors of the Assemblée open data, stored in the deputy table
export const congressVote = pgTable("congress_vote", {
  // "pollId:actorId", see senateVote
  id: text("id").primaryKey(),
  pollId: text("poll_id")
    .notNull()
    .references(() => poll.id, { onDelete: "cascade" }),
  actorId: text("actor_id")
    .notNull()
    .references(() => deputy.id),
  groupRef: text("group_ref").notNull(),
  position: text("position", {
    enum: ["for", "against", "abstention", "nonVoting"],
  }).notNull(),
});
